# Words that name almost anything; a header matched only through one of them is a weak guess.
WEAK_WORDS = frozenset({"name", "nazwa", "adres", "address", "numer", "nr", "number", "data", "type", "typ", "kod"})

_FOLD = str.maketrans({"ł": "l", "Ł": "l", "ß": "ss", "ø": "o", "æ": "ae", "œ": "oe"})


def normalise(text: str) -> str:
    """`"  Nazwa_Firmy (pełna) "` → `"nazwa firmy pelna"`: lower case, letters folded to ASCII, punctuation → space."""
    folded = unicodedata.normalize("NFKD", text.translate(_FOLD).casefold())
    ascii_text = "".join(char for char in folded if not unicodedata.combining(char))
    return re.sub(r"[^a-z0-9]+", " ", ascii_text).strip()


def compact(text: str) -> str:
    """The normalised words without spaces — `e mail` and `email` meet here."""
    return normalise(text).replace(" ", "")
